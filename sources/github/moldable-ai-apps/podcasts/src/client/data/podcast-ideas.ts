export function shuffledPodcastIdeas(): string[] {
  const ideas: string[] = [...podcastIdeas]
  for (let index = ideas.length - 1; index > 0; index--) {
    const other = Math.floor(Math.random() * (index + 1))
    ;[ideas[index], ideas[other]] = [ideas[other]!, ideas[index]!]
  }
  return ideas
}
